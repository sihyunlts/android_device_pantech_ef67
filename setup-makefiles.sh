#!/bin/bash
set -euo pipefail

DEVICE_PATH="$(cd "$(dirname "$0")" && pwd)"
ANDROID_ROOT="$(cd "$DEVICE_PATH/../../.." && pwd)"
VENDOR_PATH="$ANDROID_ROOT/vendor/pantech/ef67"

if [[ ! -f "$VENDOR_PATH/Android.mk" ]]; then
    echo "Check out vendor/pantech/ef67 before generating its blob list." >&2
    exit 1
fi

awk '
BEGIN {
    print "# Generated by device/pantech/ef67/setup-makefiles.sh."
    print ""
    printf "PRODUCT_COPY_FILES +="
}
/^(#|$|-)/ { next }
{
    printf " \\\n    vendor/pantech/ef67/proprietary/%s:system/%s", $0, $0
}
END { print "" }
' "$DEVICE_PATH/proprietary-files.txt" "$DEVICE_PATH/firmware-files.txt" > "$VENDOR_PATH/ef67-vendor-blobs.mk"
